import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { decodePng, recoverAlpha, resizeArea } from "../brand-assets/png.mjs";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "../..");
const designRoot = path.join(repoRoot, "browser/shared-ui/design/icons");
const manifest = JSON.parse(readFileSync(path.join(designRoot, "manifest.json"), "utf8"));
const output = path.join(repoRoot, "browser/cef-shell/src/browser/window/generated/alloy_icon_masks.h");
const renderRoot = path.join(repoRoot, "target/design-icons/render");
const check = process.argv.includes("--check");
const chrome = findChrome();
const sizes = [20, 40];
const productGlyphs = new Set([
  "tab.new", "tab.close", "tab.move-window", "nav.back", "nav.forward",
  "nav.reload", "nav.stop", "omnibox.site-info", "bookmark.outline",
  "bookmark.filled", "cast.device", "menu.more", "download.open",
  "history.open",
]);

mkdirSync(renderRoot, { recursive: true });
const blocks = [];
const glyphs = manifest.glyphs.filter((glyph) => productGlyphs.has(glyph.id));
if (glyphs.length !== productGlyphs.size) throw new Error("product glyph allow-set is missing from the design manifest");
for (const glyph of glyphs) {
  const svg = readSvg(glyph.file);
  const rendered = recoverAlpha(render(svg, glyph.id, "black", "#000000"), render(svg, glyph.id, "white", "#ffffff"));
  for (const size of sizes) {
    const alpha = resizeArea(rendered, size).pixels.filter((_value, index) => index % 4 === 3);
    const name = identifier(glyph.id) + (size === 20 ? "1x" : "2x");
    const rows = [];
    for (let offset = 0; offset < alpha.length; offset += 20) {
      rows.push(`    ${[...alpha.subarray(offset, offset + 20)].join(", ")}`);
    }
    blocks.push(`inline constexpr std::uint8_t ${name}[] = {\n${rows.join(",\n")}\n};`);
  }
}
const generated = `// Generated by tools/design-icons/generate-cef-masks.mjs. Do not edit.\n#pragma once\n\n#include <cstdint>\n\nnamespace crayon::browser::cef_shell::window::generated {\n\n${blocks.join("\n\n")}\n\n}  // namespace crayon::browser::cef_shell::window::generated\n`;
if (check) {
  if (!existsSync(output) || readFileSync(output, "utf8").replaceAll("\r\n", "\n") !== generated) {
    throw new Error("generated Alloy icon masks are stale; run node tools/design-icons/generate-cef-masks.mjs");
  }
} else {
  mkdirSync(path.dirname(output), { recursive: true });
  writeFileSync(output, generated);
}
process.stdout.write(`${JSON.stringify({ passed: true, glyphs: glyphs.length, scales: sizes })}\n`);

function readSvg(file) {
  const source = readFileSync(path.join(designRoot, file), "utf8");
  if (/<(?:script|style|foreignObject|image|use)\b/i.test(source) || /\b(?:href|on[a-z]+)\s*=/i.test(source)) throw new Error(`unsafe SVG: ${file}`);
  return source.replaceAll("currentColor", "#000000");
}

function render(svg, id, matte, background) {
  const htmlPath = path.join(renderRoot, `${id}.html`);
  const pngPath = path.join(renderRoot, `${id}-${matte}.png`);
  const profile = path.join(renderRoot, `${id}-${matte}-profile`);
  writeFileSync(htmlPath, `<!doctype html><meta charset="utf-8"><style>html,body{margin:0;width:100%;height:100%;overflow:hidden;background:${background}}svg{display:block;width:1024px;height:1024px}</style>${svg}`);
  const result = spawnSync(chrome, ["--headless=new", "--disable-gpu", "--hide-scrollbars", "--no-first-run", "--force-device-scale-factor=1", "--window-size=1024,1024", `--user-data-dir=${profile}`, `--screenshot=${pngPath}`, pathToFileURL(htmlPath).href], { encoding: "utf8", timeout: 30_000 });
  if (result.error) throw result.error;
  if (result.status !== 0 || !existsSync(pngPath)) throw new Error(`renderer failed for ${id}/${matte}: ${result.stderr.trim()}`);
  return decodePng(readFileSync(pngPath));
}

function identifier(id) {
  return `k${id.split(/[^a-z0-9]+/i).map((part) => part[0].toUpperCase() + part.slice(1)).join("")}`;
}

function findChrome() {
  const explicit = process.argv.find((argument) => argument.startsWith("--chrome="))?.slice(9) || process.env.CRAYON_CHROME;
  const candidates = [explicit, process.env.PROGRAMFILES && path.join(process.env.PROGRAMFILES, "Google/Chrome/Application/chrome.exe"), process.env["PROGRAMFILES(X86)"] && path.join(process.env["PROGRAMFILES(X86)"], "Google/Chrome/Application/chrome.exe"), process.env.PROGRAMFILES && path.join(process.env.PROGRAMFILES, "Microsoft/Edge/Application/msedge.exe")].filter(Boolean);
  const found = candidates.find((candidate) => existsSync(candidate));
  if (!found) throw new Error("Chrome/Edge not found; set CRAYON_CHROME");
  return found;
}
